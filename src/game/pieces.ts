export function palette(color: Color): Record<string, string> {
  return color === 'w'
    ? { '1': '#705043', '2': '#ffe8b0', '3': '#fff9e8', '4': '#edaa45' }
    : { '1': '#283348', '2': '#546987', '3': '#859bbc', '4': '#b99aff' };
}

export function pieceSvg(type: PieceSymbol, color: Color): string {
  const colors = palette(color);
  const pixels = PIECES[type].flatMap((row, y) => [...row].map((pixel, x) =>
    colors[pixel] ? `<rect x="${x}" y="${y}" width="1" height="1" fill="${colors[pixel]}"/>` : '',
  )).join('');
  return `data:image/svg+xml,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 20" shape-rendering="crispEdges">${pixels}</svg>`)}`;
}
